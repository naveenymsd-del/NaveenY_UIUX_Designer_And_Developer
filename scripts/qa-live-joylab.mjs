import { chromium } from 'playwright-core'
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', args: ['--use-angle=d3d11'] })
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage()
const errs = []; p.on('pageerror', (e) => errs.push(e.message))
await p.goto('https://naveenymsd-del.github.io/NaveenY_UIUX_Designer_And_Developer/mindspace?intro=off')
await p.waitForSelector('.ms.is-ready', { timeout: 60000 }); await sleep(2000)
const labels = await p.evaluate(() => [...document.querySelectorAll('.ms-icon__label')].map((l) => l.textContent))
await p.getByRole('button', { name: 'Open Joy Lab' }).click(); await sleep(1200)
const games = await p.evaluate(() => [...document.querySelectorAll('.jl-card h3')].map((h) => h.textContent))
await p.keyboard.press('Escape'); await sleep(600)
await p.getByRole('button', { name: 'Open Music Lounge' }).click(); await sleep(1200)
await p.locator('.mu-bar__play').click(); await sleep(2500)
const playing = await p.evaluate(() => document.querySelector('.mu-bar__play')?.getAttribute('aria-label'))
await p.screenshot({ path: 'qa-screens/live-music.png' })
console.log(JSON.stringify({ apps: labels.length, hasJoyLab: labels.includes('Joy Lab'), hasMusic: labels.includes('Music'), games, playButtonNow: playing, errors: errs }))
await b.close()
